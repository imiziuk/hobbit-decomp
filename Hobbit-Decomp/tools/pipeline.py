"""One round of the automatic decompilation pipeline:
  1. ghidra2c     Ghidra decompiler units -> standalone C files (auto/units)
  2. build_units  compile each one alone; the ones that compile go to auto/ok
  3. cmake build  DLL containing them (not yet swapped in)
  4. equiv        emulator: original vs ours on random inputs -> auto/verified.tsv
  5. gen_registry passing functions -> src/auto_registry.cpp
  6. cmake build  final DLL; copy next to Meridian.exe (unless the game is running)
Usage: python tools/pipeline.py [units_dir] [--trials N] [--no-deploy]
"""
import os, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PY = os.path.join(ROOT, "tools", ".venv", "Scripts", "python.exe")
CMAKE = r"C:\Program Files\Microsoft Visual Studio\18\Community\Common7\IDE\CommonExtensions\Microsoft\CMake\CMake\bin\cmake.exe"
GAME = os.path.join(ROOT, "..", "The.Hobbit.-.Clean", "The Hobbit - Clean")

def run(*cmd):
    print(">", " ".join(str(c) for c in cmd), flush=True)
    subprocess.run([str(c) for c in cmd], cwd=ROOT, check=True)

def build_dll():
    """cmake build; if the link fails on some generated units, drop those units and retry."""
    import re
    for attempt in range(5):
        r = subprocess.run([CMAKE, "--build", "build", "--config", "Release", "--parallel"], cwd=ROOT,
                           capture_output=True, text=True)
        print(r.stdout[-2000:], flush=True)
        if r.returncode == 0:
            return
        bad = set(re.findall(r"([0-9a-f]{8})\.obj : error LNK", r.stdout))
        if not bad:
            raise SystemExit("DLL build failed (not a generated unit)")
        for a in bad:
            p = os.path.join(ROOT, "auto", "ok", f"{a}.c")
            if os.path.exists(p):
                os.remove(p)
        print(f"dropped {len(bad)} units that failed to link: {sorted(bad)}", flush=True)
    raise SystemExit("DLL build still failing")

def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    units = args[0] if args else os.path.join(ROOT, "..", "Hobbit-RE", "db", "units")
    trials = sys.argv[sys.argv.index("--trials") + 1] if "--trials" in sys.argv else "20"
    os.environ["HOBBIT_UNITS"] = os.path.abspath(units)     # equiv.py reads callee signatures from here
    header = os.path.join(ROOT, "..", "Hobbit-RE", "db", "cexport2", "meridian.h")
    reg = os.path.join(ROOT, "src", "auto_registry.cpp")
    if "--resume" not in sys.argv:   # --resume: keep the tested DLL, continue the equivalence step
        run(PY, "tools/ghidra2c.py", units, header)
        run(PY, "tools/build_units.py")
        with open(reg, "w", encoding="utf-8") as f:      # stage 1 DLL: no generated function swapped in yet
            f.write("// GENERATED by tools/gen_registry.py — empty while testing\n")
        build_dll()
        cache = os.path.join(ROOT, "auto", "callee_sigs.json")
        if os.path.exists(cache):
            os.remove(cache)
    run(PY, "tools/equiv.py", "--auto", "--trials", trials, "--quiet")
    run(PY, "tools/gen_registry.py")
    build_dll()
    run(PY, "tools/check_hooks.py")
    if "--no-deploy" not in sys.argv:
        running = subprocess.run(["tasklist", "/FI", "IMAGENAME eq Meridian.exe"], capture_output=True, text=True)
        if "Meridian.exe" in running.stdout:
            print("game is running: DLL not copied")
        else:
            shutil.copy(os.path.join(ROOT, "build", "Release", "dinput8.dll"), GAME)
            print("deployed dinput8.dll")

if __name__ == "__main__":
    main()
